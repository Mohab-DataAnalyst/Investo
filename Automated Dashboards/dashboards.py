import pandas as pd
import numpy as np
from datetime import datetime


# ══════════════════════════════════════════════════════════════════════
#  DASHBOARD 1 — Startup Performance
#  Who calls it: startup profile page
#  What it answers: how is this startup performing?
#
#  Note: risk_level is not in startup_data_with_graph.csv — it is a
#  model output stored separately in the DB after the async prediction
#  job. Dashboards work purely from CSV data.
# ══════════════════════════════════════════════════════════════════════

def get_startup_dashboard(startup_name, startups_df):
    startup = startups_df[startups_df['startup_name'] == startup_name]
    if startup.empty:
        return {"error": f"Startup '{startup_name}' not found."}
    startup = startup.iloc[0]

    current_year      = datetime.now().year
    startup_age       = current_year - int(startup['founded_year'])
    industry_startups = startups_df[startups_df['industry'] == startup['industry']]

    return {
        # Core ML score
        "success_score": int(startup['success_score']),

        # Derived financial metrics
        "revenue_per_employee": round(
            float(startup['annual_revenue']) / max(float(startup['no_employees']), 1), 4
        ),
        "funding_efficiency": round(
            float(startup['annual_revenue']) / max(float(startup['total_funding']), 1), 4
        ),
        "valuation_multiple": round(
            float(startup['valuation']) / max(float(startup['total_funding']), 1), 4
        ),

        # Traction
        "social_traction_score": round(
            float(startup['social_media_followers']) + float(startup['customer_base']), 4
        ),
        "startup_age": startup_age,

        # Exit flags
        "ipo":      bool(startup['ipo']),
        "acquired": bool(startup['acquired']),

        # Network position
        "degree_centrality":      round(float(startup['degree_centrality']), 4),
        "betweenness_centrality": round(float(startup['betweenness_centrality']), 4),
        "community_id":           int(startup['community_id']),

        # Industry ranking — percentile of success_score within same industry
        "industry_percentile_ranking": round(
            float(
                (industry_startups['success_score'] < startup['success_score']).mean() * 100
            ), 2
        ),
    }


# ══════════════════════════════════════════════════════════════════════
#  DASHBOARD 2 — Investor Portfolio
#  Who calls it: investor profile page
#  What it answers: how is this investor's portfolio composed?
# ══════════════════════════════════════════════════════════════════════

def get_investor_dashboard(investor_id, investors_df, startups_df, interactions_df):
    investor = investors_df[investors_df['investor_id'] == investor_id]
    if investor.empty:
        return {"error": f"Investor '{investor_id}' not found."}
    investor = investor.iloc[0]

    # Get portfolio startup names from interactions table
    portfolio_names = interactions_df[
        interactions_df['investor_id'] == investor_id
    ]['startup_name'].tolist()

    if not portfolio_names:
        return {"error": "Investor has no portfolio investments."}

    portfolio = startups_df[startups_df['startup_name'].isin(portfolio_names)]

    if portfolio.empty:
        return {"error": "No matching startups found for portfolio."}

    return {
        "investor_id":        investor_id,
        "preferred_industry": investor['preferred_industry'],
        "risk_tolerance":     investor['risk_tolerance'],
        "portfolio_size":     len(portfolio_names),

        # Composition
        "industry_distribution": portfolio['industry'].value_counts(normalize=True).round(4).to_dict(),
        "stage_allocation":      portfolio['funding_stage'].value_counts(normalize=True).round(4).to_dict(),
        "country_distribution":  portfolio['country'].value_counts(normalize=True).round(4).to_dict(),

        # Performance
        "avg_success_score":              round(float(portfolio['success_score'].mean()), 2),
        "capital_allocation_by_industry": portfolio.groupby('industry')['total_funding'].sum().round(2).to_dict(),

        # Network
        "avg_degree_centrality":      round(float(portfolio['degree_centrality'].mean()), 4),
        "avg_betweenness_centrality": round(float(portfolio['betweenness_centrality'].mean()), 4),
    }


# ══════════════════════════════════════════════════════════════════════
#  DASHBOARD 3 — Market Intelligence
#  Who calls it: market overview / explore page
#  What it answers: what does the startup landscape look like?
#
#  Success: success_score >= 7 (top third of 1-9 scale)
#  risk_level removed — not in CSV, stored in DB as model output.
# ══════════════════════════════════════════════════════════════════════

def get_market_dashboard(startups_df):
    df = startups_df.copy()

    current_year      = datetime.now().year
    df['startup_age'] = current_year - df['founded_year']

    # Success: top third of success score scale
    df['success'] = (df['success_score'] >= 7).astype(int)

    # Industry average revenue
    industry_avg_revenue  = df.groupby('industry')['annual_revenue'].mean().round(2).to_dict()

    # Industry average success score
    industry_success_rate = df.groupby('industry')['success_score'].mean().round(2).to_dict()

    # Country average success score
    country_success_rate  = df.groupby('country')['success_score'].mean().round(2).to_dict()

    # Funding vs valuation — sample 500 points to keep response size manageable
    funding_valuation = (
        df[['startup_name', 'total_funding', 'valuation', 'industry']]
        .sample(min(500, len(df)), random_state=42)
        .round(2)
        .to_dict(orient='records')
    )

    # Average success score by funding stage
    success_by_stage = df.groupby('funding_stage')['success_score'].mean().round(2).to_dict()

    # Average total funding by stage
    funding_by_stage = df.groupby('funding_stage')['total_funding'].mean().round(2).to_dict()

    # Industry count
    industry_count = df['industry'].value_counts().to_dict()

    # Country count
    country_count = df['country'].value_counts().to_dict()

    return {
        "industry_avg_revenue":   industry_avg_revenue,
        "industry_success_rate":  industry_success_rate,
        "country_success_rate":   country_success_rate,
        "funding_vs_valuation":   funding_valuation,
        "success_score_by_stage": success_by_stage,
        "avg_funding_by_stage":   funding_by_stage,
        "industry_count":         industry_count,
        "country_count":          country_count,
    }


# ══════════════════════════════════════════════════════════════════════
#  DASHBOARD 4 — Risk Insights
#  Who calls it: risk analysis page
#  What it answers: what drives risk and failure?
#
#  Failure: success_score <= 4 (bottom third of 1-9 scale)
#  risk_level removed — not in CSV, stored in DB as model output.
#  risk_by_industry and success_score_by_risk removed accordingly.
#  Replaced with success_score_by_industry and failure_rate_by_industry.
# ══════════════════════════════════════════════════════════════════════

def get_risk_dashboard(startups_df):
    df = startups_df.copy()

    current_year      = datetime.now().year
    df['startup_age'] = current_year - df['founded_year']

    # Failure: bottom third of success score scale
    df['failure'] = (df['success_score'] <= 4).astype(int)

    # Failure rate by funding stage
    failure_by_stage = df.groupby('funding_stage')['failure'].mean().round(4).to_dict()

    # Failure rate by funding size quartile
    try:
        df['funding_quartile'] = pd.qcut(
            df['total_funding'],
            q=4,
            duplicates='drop'
        )
        failure_by_funding = (
            df.groupby('funding_quartile', observed=True)['failure']
            .mean()
            .round(4)
            .to_dict()
        )
        failure_by_funding = {str(k): v for k, v in failure_by_funding.items()}
    except ValueError:
        failure_by_funding = {}

    # Survival rate by startup age group
    df['age_group'] = pd.cut(
        df['startup_age'],
        bins=[0, 2, 5, 10, 20, 100],
        labels=['0-2 yrs', '3-5 yrs', '6-10 yrs', '11-20 yrs', '20+ yrs'],
        right=True
    )
    survival_by_age = (
        (1 - df.groupby('age_group', observed=True)['failure'].mean())
        .round(4)
        .to_dict()
    )
    survival_by_age = {str(k): v for k, v in survival_by_age.items()}

    # Average success score by industry
    success_by_industry = df.groupby('industry')['success_score'].mean().round(2).to_dict()

    # Failure rate by industry
    failure_by_industry = df.groupby('industry')['failure'].mean().round(4).to_dict()

    return {
        "failure_rate_by_stage":     failure_by_stage,
        "failure_rate_by_funding":   failure_by_funding,
        "survival_rate_by_age":      survival_by_age,
        "success_score_by_industry": success_by_industry,
        "failure_rate_by_industry":  failure_by_industry,
    }
