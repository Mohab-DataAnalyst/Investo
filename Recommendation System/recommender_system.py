import pandas as pd
import numpy as np
import joblib
import os
from scipy.sparse import csr_matrix
from sklearn.preprocessing import LabelEncoder, MinMaxScaler
from sklearn.metrics.pairwise import cosine_similarity
from implicit.als import AlternatingLeastSquares
from DataAccess.db import load_startups, load_investors, load_interactions

# Load Data
startups_df     = load_startups()
investors_df    = load_investors()
interactions_df = load_interactions()


def _normalize_text(series, default="unknown"):
    return (
        series.fillna("")
        .astype(str)
        .str.strip()
        .str.lower()
        .replace("", default)
    )


def _fill_numeric(df, column, default):
    df[column] = pd.to_numeric(df[column], errors="coerce").fillna(default)


def _encode_known_or_neutral(encoder, values):
    class_to_index = {value: index for index, value in enumerate(encoder.classes_)}
    denominator = max(len(encoder.classes_), 1)
    return np.array(
        [
            class_to_index[value] / denominator
            if value in class_to_index
            else 0.5
            for value in values
        ],
        dtype=float,
    )


for col in ["industry", "country", "funding_stage"]:
    startups_df[col] = _normalize_text(startups_df[col])
startups_df["startup_name"] = startups_df["startup_name"].fillna("").astype(str)
startups_df["risk_level"] = _normalize_text(startups_df["risk_level"], "medium")
startups_df["community_id"] = (
    pd.to_numeric(startups_df["community_id"], errors="coerce")
    .fillna(0)
    .astype(int)
    .astype(str)
)

investors_df["preferred_industry"] = _normalize_text(
    investors_df["preferred_industry"],
    "",
)
investors_df["country_preference"] = _normalize_text(
    investors_df["country_preference"],
    "",
)
investors_df["risk_tolerance"] = _normalize_text(
    investors_df["risk_tolerance"],
    "medium",
)
investors_df["investor_id"] = investors_df["investor_id"].fillna("").astype(str)
interactions_df["investor_id"] = interactions_df["investor_id"].fillna("").astype(str)
interactions_df["startup_name"] = interactions_df["startup_name"].fillna("").astype(str)

_fill_numeric(startups_df, "success_score", 5)
_fill_numeric(startups_df, "total_funding", 0)
_fill_numeric(startups_df, "no_employees", 0)
_fill_numeric(startups_df, "degree_centrality", 0)
_fill_numeric(startups_df, "betweenness_centrality", 0)

max_startup_funding = float(startups_df["total_funding"].max()) if len(startups_df) else 0
_fill_numeric(investors_df, "min_success_score_preferred", 5)
_fill_numeric(investors_df, "min_investment", 0)
_fill_numeric(investors_df, "max_investment", max(max_startup_funding, 1))

# Shared Mappers
n_investors = interactions_df['investor_id'].nunique()
n_startups  = interactions_df['startup_name'].nunique()

startup_name_to_idx = dict(zip(interactions_df['startup_name'].unique(), range(n_startups)))
startup_idx_to_name = dict(zip(range(n_startups), interactions_df['startup_name'].unique()))
investor_id_to_idx  = dict(zip(interactions_df['investor_id'].unique(), range(n_investors)))
investor_idx_to_id  = dict(zip(range(n_investors), interactions_df['investor_id'].unique()))

startup_lookup         = startups_df.set_index('startup_name')
investor_lookup        = investors_df.set_index('investor_id')
startup_name_to_df_idx = dict(zip(startups_df['startup_name'], range(len(startups_df))))
investor_id_to_df_idx  = dict(zip(investors_df['investor_id'], range(len(investors_df))))

#  SYSTEM 1 — CONTENT-BASED (user×item cosine similarity)

# Encoders & Scalers
_le_industry  = LabelEncoder().fit(startups_df['industry'])
_le_country   = LabelEncoder().fit(startups_df['country'])
_le_stage     = LabelEncoder().fit(startups_df['funding_stage'])
_le_risk      = LabelEncoder().fit(startups_df['risk_level'])
_le_community = LabelEncoder().fit(startups_df['community_id'].astype(str))

_scaler_funding   = MinMaxScaler().fit(startups_df[['total_funding']])
_scaler_employees = MinMaxScaler().fit(startups_df[['no_employees']])
_scaler_score     = MinMaxScaler().fit(startups_df[['success_score']])
_scaler_inv_score = MinMaxScaler().fit(investors_df[['min_success_score_preferred']])

_risk_order = {'low': 0.0, 'medium': 0.5, 'high': 1.0}

# Startup feature matrix
startup_feature_matrix = np.column_stack([
    _le_industry.transform(startups_df['industry'])                   / len(_le_industry.classes_),
    _le_country.transform(startups_df['country'])                     / len(_le_country.classes_),
    _le_stage.transform(startups_df['funding_stage'])                 / len(_le_stage.classes_),
    _le_risk.transform(startups_df['risk_level'])                     / len(_le_risk.classes_),
    _le_community.transform(startups_df['community_id'].astype(str)) / len(_le_community.classes_),
    _scaler_score.transform(startups_df[['success_score']]).ravel(),
    _scaler_funding.transform(startups_df[['total_funding']]).ravel(),
    _scaler_employees.transform(startups_df[['no_employees']]).ravel(),
    startups_df['degree_centrality'].values,       # already 0-1
    startups_df['betweenness_centrality'].values,  # already 0-1
])

# ── Investor preference matrix
# investment_midpoint: midpoint of investor's min/max investment range,
# normalized using the same _scaler_funding fitted on startup total_funding
# so both sides are on the same scale for cosine similarity to work correctly.
#
# Columns with no investor equivalent are padded with 0.5 (neutral)
_inv_midpoint        = (investors_df['min_investment'] + investors_df['max_investment']) / 2
_inv_midpoint_scaled = _scaler_funding.transform(
    pd.DataFrame({"total_funding": _inv_midpoint})
).ravel()

investor_feature_matrix = np.column_stack([
    _encode_known_or_neutral(_le_industry, investors_df['preferred_industry']),
    _encode_known_or_neutral(_le_country, investors_df['country_preference']),
    np.full(len(investors_df), 0.5),                            # funding_stage → neutral
    np.array([_risk_order.get(r, 0.5) for r in investors_df['risk_tolerance']]),
    np.full(len(investors_df), 0.5),                            # community_id → neutral
    _scaler_inv_score.transform(investors_df[['min_success_score_preferred']]).ravel(),
    _inv_midpoint_scaled,                                       # investment midpoint ↔ total_funding
    np.full(len(investors_df), 0.5),                            # no_employees → neutral
    np.full(len(investors_df), 0.5),                            # degree_centrality → neutral
    np.full(len(investors_df), 0.5),                            # betweenness_centrality → neutral
])

# user×item content similarity matrix
content_sim_matrix = cosine_similarity(investor_feature_matrix, startup_feature_matrix)

# item×item cosine similarity (for find_similar_startups)
item_cosine_sim = cosine_similarity(startup_feature_matrix, startup_feature_matrix)

# find similar startups
def find_similar_startups(startup_name, n_recommendations=5):
    if startup_name not in startup_name_to_df_idx:
        raise ValueError(f"Startup '{startup_name}' not found.")

    idx        = startup_name_to_df_idx[startup_name]
    sim_scores = list(enumerate(item_cosine_sim[idx]))
    sim_scores = sorted(sim_scores, key=lambda x: x[1], reverse=True)
    
    # Filter out the requested startup itself
    filtered_sim_scores = [(i, score) for i, score in sim_scores if startups_df.iloc[i]['startup_name'] != startup_name]
    sim_scores = filtered_sim_scores[:n_recommendations]

    return [{
        'startup_name':           startups_df.iloc[i]['startup_name'],
        'similarity_score':       round(float(score), 4),
        'industry':               startups_df.iloc[i]['industry'],
        'country':                startups_df.iloc[i]['country'],
        'funding_stage':          startups_df.iloc[i]['funding_stage'],
        'risk_level':             startups_df.iloc[i]['risk_level'],
        'success_score':          int(startups_df.iloc[i]['success_score']),
        'total_funding':          round(float(startups_df.iloc[i]['total_funding']), 1),
        'funding_required':       round(float(startups_df.iloc[i]['funding_required'] if not pd.isna(startups_df.iloc[i]['funding_required']) else 0.0), 1),
        'community_id':           int(startups_df.iloc[i]['community_id']),
        'degree_centrality':      round(float(startups_df.iloc[i]['degree_centrality']), 4),
        'betweenness_centrality': round(float(startups_df.iloc[i]['betweenness_centrality']), 4),
    } for i, score in sim_scores]

#  SYSTEM 2 — COLLABORATIVE FILTERING (Implicit ALS)

# create X matrix
def create_X(df):
    investor_idx = [investor_id_to_idx[i] for i in df['investor_id']]
    startup_idx  = [startup_name_to_idx[s] for s in df['startup_name']]
    X = csr_matrix(
        (df['invested'].astype(np.float32), (investor_idx, startup_idx)),
        shape=(n_investors, n_startups)
    )
    return X

X = create_X(interactions_df)

als_model = AlternatingLeastSquares(
    factors=50,
    regularization=0.01,
    iterations=30,
    calculate_training_loss=True,
    random_state=42
)
als_model.fit(X, show_progress=False)

#  HYBRID RECOMMENDATIONS
#  final_score = 0.95 * ALS + 0.05 * content  (known investors)
#  final_score = 1.00 * content                (cold start)

# investor to startup recommendation function
def investor_to_startups_recommendations(investor_id, n_recommendations=5):
    if investor_id not in investor_lookup.index:
        raise ValueError(f"Investor '{investor_id}' not found.")

    inv_idx       = investor_id_to_idx.get(investor_id)
    inv_df_idx    = investor_id_to_df_idx[investor_id]
    is_cold_start = inv_idx is None or X[inv_idx].nnz == 0

    investor_min_inv = float(investors_df.iloc[inv_df_idx]['min_investment'])
    investor_max_inv = float(investors_df.iloc[inv_df_idx]['max_investment'])

    # Already-invested startup df indices to exclude
    already_invested_df_idx = set()
    if inv_idx is not None:
        invested_cols = X[inv_idx].nonzero()[1]
        already_invested_df_idx = {
            startup_name_to_df_idx[startup_idx_to_name[c]]
            for c in invested_cols if startup_idx_to_name[c] in startup_name_to_df_idx
        }

    # Content scores — one row from user×item matrix, shape: (n_all_startups,)
    content_scores = content_sim_matrix[inv_df_idx]

    # ALS scores normalized to 0-1, stored by startup df index
    als_scores = np.full(len(startups_df), np.nan)
    if not is_cold_start:
        item_ids, raw_scores = als_model.recommend(
            userid=inv_idx,
            user_items=X[inv_idx],
            N=n_startups,
            filter_already_liked_items=True
        )
        if len(raw_scores) > 0:
            s_min, s_max = raw_scores.min(), raw_scores.max()
            denom = max(float(s_max - s_min), 1e-9)
            for i, item_id in enumerate(item_ids):
                name = startup_idx_to_name.get(int(item_id))
                if name and name in startup_name_to_df_idx:
                    als_scores[startup_name_to_df_idx[name]] = (raw_scores[i] - s_min) / denom

    # Build final scores — vectorized
    has_als      = ~np.isnan(als_scores)
    final_scores = np.where(
        has_als,
        0.95 * als_scores + 0.05 * content_scores,
        content_scores
    ) if not is_cold_start else content_scores.copy()

    # Exclude already-invested startups
    final_scores[list(already_invested_df_idx)] = -np.inf

    # Hard filter — exclude startups outside investor's investment range
    funding_values = startups_df['total_funding'].values
    out_of_range   = ~((funding_values >= investor_min_inv) & (funding_values <= investor_max_inv))
    final_scores[out_of_range] = -np.inf

    top_indices = np.argsort(final_scores)[-n_recommendations:][::-1]
    top_indices = [i for i in top_indices if final_scores[i] != -np.inf]

    return [{
        'startup_name':           startups_df.iloc[i]['startup_name'],
        'industry':               startups_df.iloc[i]['industry'],
        'country':                startups_df.iloc[i]['country'],
        'funding_stage':          startups_df.iloc[i]['funding_stage'],
        'total_funding':          round(float(startups_df.iloc[i]['total_funding']), 1),
        'funding_required':       round(float(startups_df.iloc[i]['funding_required'] if not pd.isna(startups_df.iloc[i]['funding_required']) else 0.0), 1),
        'success_score':          int(startups_df.iloc[i]['success_score']),
        'risk_level':             startups_df.iloc[i]['risk_level'],
        'community_id':           int(startups_df.iloc[i]['community_id']),
        'degree_centrality':      round(float(startups_df.iloc[i]['degree_centrality']), 4),
        'betweenness_centrality': round(float(startups_df.iloc[i]['betweenness_centrality']), 4),
        'final_score':            round(float(final_scores[i]), 4),
        'als_score':              round(float(als_scores[i]), 4) if not np.isnan(als_scores[i]) else None,
        'content_score':          round(float(content_scores[i]), 4),
        'cold_start':             is_cold_start,
    } for i in top_indices]

