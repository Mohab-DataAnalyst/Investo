from functools import lru_cache
from fastapi import APIRouter, FastAPI, HTTPException
from pydantic import BaseModel
from typing import List, Optional

router = APIRouter(
    prefix="/recommendations",
    tags=["recommendations"],
)


@lru_cache(maxsize=1)
def _load_recommender_service():
    from . import recommender_system

    return recommender_system


def _get_recommender_service():
    try:
        return _load_recommender_service()
    except Exception as e:
        raise HTTPException(
            status_code=503,
            detail=f"Recommender service unavailable: {e}",
        ) from e


# Request Schemas

class SimilarStartupsInput(BaseModel):
    startup_name: str
    n_recommendations: int = 5

class InvestorInput(BaseModel):
    investor_id: str
    n_recommendations: int = 5


# Response Schemas

class SimilarStartup(BaseModel):
    startup_name:           str
    similarity_score:       float
    industry:               str
    country:                str
    funding_stage:          str
    risk_level:             str
    success_score:          int
    total_funding:          float
    funding_required:       float
    community_id:           int
    degree_centrality:      float
    betweenness_centrality: float

class StartupMatch(BaseModel):
    startup_name:           str
    industry:               str
    country:                str
    funding_stage:          str
    total_funding:          float
    funding_required:       float
    success_score:          int
    risk_level:             str
    community_id:           int
    degree_centrality:      float
    betweenness_centrality: float
    final_score:            float
    als_score:              Optional[float]
    content_score:          float
    cold_start:             bool


# Endpoints

@router.post("/similar-startups", response_model=List[SimilarStartup])
def similar_startups(data: SimilarStartupsInput):
    recommender_service = _get_recommender_service()
    try:
        return recommender_service.find_similar_startups(
            data.startup_name,
            data.n_recommendations,
        )

    except (KeyError, ValueError) as e:
        raise HTTPException(status_code=404, detail=str(e)) from e
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e)) from e


@router.post("/investor-to-projects", response_model=List[StartupMatch])
def investor_to_projects(data: InvestorInput):
    recommender_service = _get_recommender_service()
    try:
        return recommender_service.investor_to_startups_recommendations(
            data.investor_id,
            data.n_recommendations,
        )

    except (KeyError, ValueError) as e:
        raise HTTPException(status_code=404, detail=str(e)) from e
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e)) from e


# Health Check

@router.get("/")
def health():
    try:
        recommender_service = _load_recommender_service()
        return {
            "status": "Recommendations API is running",
            "service_loaded": True,
            "investors": len(recommender_service.investors_df),
            "startups": len(recommender_service.startups_df),
            "interactions": int(recommender_service.X.nnz),
        }
    except Exception as e:
        return {
            "status": "Recommendations API is unavailable",
            "service_loaded": False,
            "detail": str(e),
        }


def create_app() -> FastAPI:
    app = FastAPI(title="Startup Recommendation API")
    app.include_router(router)
    return app


app = create_app()
