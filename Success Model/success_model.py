# ── Custom Transformer ────────────────────────────────────────────────
class MultiLabelBinarizerTransformer(BaseEstimator, TransformerMixin):
    """Pipeline-compatible wrapper for MultiLabelBinarizer on a single string column."""

    def __init__(self, prefix='tech'):
        self.prefix = prefix

    def _to_lists(self, series):
        def parse(x):
            if isinstance(x, list):
                return [str(t).strip() for t in x if str(t).strip()]
            return [t.strip() for t in str(x).split(',') if t.strip()]
        return series.fillna('').apply(parse)

    def _get_col(self, X):
        if hasattr(X, 'iloc'):
            return X.iloc[:, 0]
        arr = np.asarray(X)
        return pd.Series(arr[:, 0] if arr.ndim == 2 else arr)

    def fit(self, X, y=None):
        self.mlb_ = MultiLabelBinarizer()
        self.mlb_.fit(self._to_lists(self._get_col(X)))
        return self

    def transform(self, X, y=None):
        return self.mlb_.transform(self._to_lists(self._get_col(X)))

    def get_feature_names_out(self, input_features=None):
        if not hasattr(self, 'mlb_'):
            raise AttributeError("MultiLabelBinarizerTransformer is not fitted yet. Call 'fit' first.")
        return np.array([f"{self.prefix}_{c}" for c in self.mlb_.classes_])

